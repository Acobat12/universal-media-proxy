import VOTClient from "../../client";

const encoder = new TextEncoder();
const ALLOWED_HEADER = /^(?:sec-vtrans-[a-z0-9-]+|sec-vsubs-[a-z0-9-]+|vtrans-[a-z0-9-]+|vsubs-[a-z0-9-]+|sec-ch-ua(?:-[a-z0-9-]+)?|accept-language|authorization|pragma|cache-control)$/;

function varint(value: number): number[] {
  if (!Number.isSafeInteger(value) || value < 0) throw new Error("Invalid protobuf length");
  const bytes: number[] = [];
  do {
    const low = value % 128;
    value = Math.floor(value / 128);
    bytes.push(value ? low | 128 : low);
  } while (value);
  return bytes;
}
function field(tag: number, data: Uint8Array): Uint8Array {
  const length = varint(data.byteLength);
  const result = new Uint8Array(1 + length.length + data.byteLength);
  result[0] = tag;
  result.set(length, 1);
  result.set(data, 1 + length.length);
  return result;
}
function concat(parts: Uint8Array[]): Uint8Array {
  const result = new Uint8Array(parts.reduce((sum, part) => sum + part.length, 0));
  let offset = 0;
  for (const part of parts) { result.set(part, offset); offset += part.length; }
  return result;
}
export function encodeVotEnvelope(headers: Record<string, string>, body: Uint8Array, path: string, sourceVideoUrl?: string): Uint8Array {
  const parts: Uint8Array[] = [];
  for (const [key, value] of Object.entries(headers)) {
    const name = key.toLowerCase();
    if (!ALLOWED_HEADER.test(name) || typeof value !== "string" || value.length > 4096 || /[\x00-\x1f\x7f]/.test(value)) continue;
    const entry = concat([field(10, encoder.encode(name)), field(18, encoder.encode(value))]);
    parts.push(field(10, entry));
  }
  parts.push(field(18, body));
  parts.push(field(26, encoder.encode(path)));
  if (path === "/video-translation/translate" && sourceVideoUrl) parts.push(field(34, encoder.encode(sourceVideoUrl)));
  return concat(parts);
}

// Use the local VOTClient: it preserves session signatures, errors and abort handling.
export default class VOTProtobufEnvelopeClient extends VOTClient {
  // VOT may classify .m4a as a custom link and call requestVOT(JSON).
  // Only the trusted Bilibili UMP media URL must take the binary request path.
  override isCustomLink(url: string): boolean {
    const isBilibiliPage =
      typeof location !== "undefined" &&
      /(?:^|\.)bilibili\.com$/i.test(location.hostname);
    const isBilibiliMedia =
      /^https:\/\/media-proxy\.freedynamicdns\.org\/media\/bilibili\//i.test(url);

    if (isBilibiliPage && isBilibiliMedia) {
      console.info("[FORK][bilibili] forcing protobuf translation path", { url });
      return false;
    }
    return super.isCustomLink(url);
  }

  override async request<T = ArrayBuffer>(
    path: string,
    body: Uint8Array,
    headers: Record<string, string> = {},
    method = "POST",
  ) {
    // The path INSIDE the envelope must not contain the external /vot prefix.
    // Capture the effective headers generated by the underlying VOT client,
    // rather than only the explicit per-request headers. Normalize to plain
    // strings before encoding; protobuf headers cannot contain objects.
    const opts = this.getOpts(new Blob([body]), headers, method);
    const effectiveHeaders: Record<string, string> = {};
    const rawHeaders = opts.headers;
    if (rawHeaders instanceof Headers) {
      rawHeaders.forEach((value, key) => { effectiveHeaders[key] = value; });
    } else if (Array.isArray(rawHeaders)) {
      for (const entry of rawHeaders) {
        if (Array.isArray(entry) && entry.length === 2 && typeof entry[0] === "string" && typeof entry[1] === "string") {
          effectiveHeaders[entry[0]] = entry[1];
        }
      }
    } else if (rawHeaders && typeof rawHeaders === "object") {
      for (const [key, value] of Object.entries(rawHeaders)) {
        if (typeof value === "string") effectiveHeaders[key] = value;
      }
    }
    // Preserve explicitly supplied signed headers in case getOpts omits them.
    Object.assign(effectiveHeaders, headers);
    const sourceVideoUrl = path === "/video-translation/translate" && typeof location !== "undefined"
      && /^(?:www\.)?bilibili\.com$/i.test(location.hostname)
      && /^\/(?:[a-z]{2}(?:-[A-Za-z]{2,8})?\/)?video\/BV[A-Za-z0-9]+(?:\/|$)/i.test(location.pathname)
      ? location.href : undefined;
    const envelope = encodeVotEnvelope(effectiveHeaders, body, path, sourceVideoUrl);
    return super.request<T>(path, envelope, {
      "Content-Type": "application/x-vot-envelope+protobuf",
    }, method);
  }
}
